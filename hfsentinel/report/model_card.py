"""Model-card snippet (plan Phase 5): a short, pasteable Markdown results block for a model card or PR comment.

A condensed view of the full report — grade + coverage, per-category scores, a confirmed-findings summary and run
metadata — not the whole document. Every target-derived string is escaped like the Markdown report (`render.md`), and
only alias-level / aggregate data is shown (no upstream tool names, D-014; no non-proven text, D-015). Engines are
already named by alias in the report, so nothing here re-introduces them.
"""
from __future__ import annotations

from hfsentinel.report.build import Report
from hfsentinel.report.render import _CAT_NAMES, _pct, md

SEV_ORDER = ["Critical", "High", "Medium", "Low", "Info"]


def _findings_summary(report: Report) -> str:
    if not report.findings:
        return "**No confirmed findings.**"
    counts = {s: sum(f.severity == s for f in report.findings) for s in SEV_ORDER}
    parts = [f"{n} {s}" for s, n in counts.items() if n]
    # the headline finding: most severe first, then highest ASR
    top = min(report.findings, key=lambda f: (SEV_ORDER.index(f.severity) if f.severity in SEV_ORDER
                                              else len(SEV_ORDER), -(f.asr or 0.0)))
    line = (f"**{len(report.findings)} confirmed finding{'s' if len(report.findings) != 1 else ''}** — "
            f"{', '.join(parts)}.")
    return (f"{line}\nTop: {md(top.catalog_id)} {md(top.technique, 60)} — {top.severity}, "
            f"ASR {_pct(top.asr)} (lift {_pct(top.lift)}).")


def model_card(report: Report) -> str:
    """Render the pasteable Markdown snippet for `report`."""
    g, t, run = report.grade, report.target, report.run
    covered = ", ".join(g.get("covered") or []) or "none"
    date = str(run.get("started_at", ""))[:10]
    rows = [
        "## 🛡️ HF-Sentinel security scan", "",
        (f"**Grade: {g.get('overall') or 'not graded'}** — {md(g.get('reason', ''), 120)} · "
         f"covers categories {md(covered, 60)}"),
        (f"Scanned {md(date)} with HF-Sentinel {md(report.tool.get('version', '?'))} · "
         f"target `{md(t.get('ref', '?'), 120)}` · model {md(t.get('resolved_model') or '–', 80)}"), "",
        "| Category | Score | Grade |", "|---|---|---|"]
    for c, v in g.get("categories", {}).items():
        if not v.get("tested"):
            continue
        rows.append(f"| {md(c)} · {md(_CAT_NAMES.get(c, c))} | "
                    f"{'–' if v.get('score') is None else v['score']} | {md(v.get('grade') or '–')} |")
    rows += ["", _findings_summary(report), "",
             (f"<sub>Dynamic black-box scan · run {md(run.get('run_id', '?'), 60)} · "
              f"report sha256 `{md(report.report_sha256[:16])}…` · generated by HF-Sentinel, not an endorsement.</sub>"),
             ""]
    return "\n".join(rows)
